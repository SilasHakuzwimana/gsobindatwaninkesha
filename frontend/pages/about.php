      <h1>Our school History</h1>
      <div id="row" class="textpar">
        <p>The Groupe Scolaire Officiel de Butare (GSOB) Indatwa n'inkesha, also known as the Indatwa
          n'Inkesha School,
          is a historic secondary school in Huye District in Butare (formerly Astrida),
          Rwanda. As well as being the oldest secondary school in the country,
          it is regarded as one of the most prestigious and successful public schools in Rwanda. The school,
          originally known as the Groupe Scolaire d'Astrida, was established by the Brothers of
          Charity in 1929. It was intended to educate students who would form an élite to serve as chiefs and
          medical,
          agricultural,
          and veterinary assistants in the Belgian mandatory administration in Ruanda-Urundi.</p>
        <p>It took students,
          often the children of chiefs and other dignitaries,
          from both modern-day Rwanda and Burundi. Between 1932 and 1957,
          the Groupe Scolaire d'Astrida admitted 964 students from Rwanda. After independence,
          the school was renamed the Groupe Scolaire de Butare. This school is regarded as one of the most
          selective schools in Rwanda.</p>
      </div>
